import {chromium} from '@playwright/test';
const [,,out]=process.argv;
const b=await chromium.launch({channel:'chrome'});
const p=await b.newPage({viewport:{width:1280,height:900}});
const errs=[];p.on('pageerror',e=>errs.push(String(e)));p.on('console',m=>{if(m.type()==='error')errs.push(m.text());});
await p.goto('http://127.0.0.1:4173/?storage-test=1',{waitUntil:'networkidle'});
await p.waitForTimeout(2200);
await p.click('#demo-btn');await p.waitForTimeout(2500);
await p.click('#close-inspector').catch(()=>{});
const spot=await p.evaluate(()=>{const t=window.__townDebug.town(),taken=new Set();for(const b of t.buildings)for(const c of (b.footprint||[{x:b.x,z:b.z}]))taken.add(c.x+','+c.z);for(const r of t.roads)taken.add(r);
 for(let x=-8;x<=1;x++)for(let z=-6;z<=5;z++){let ok=true;for(const dx of [0,1])for(const dz of [0,1])if(taken.has((x+dx)+','+(z+dz)))ok=false;if(ok){const cells=[];for(const dx of [0,1])for(const dz of [0,1])cells.push({x:x+dx,z:z+dz});const b=t.place('garden',cells,true,'townOffice');if(b){for(const bd of t.buildings)if(bd.design==='townOffice')bd.stage=3;return {x,z,ok:true};}}}return {ok:false};});
await p.waitForTimeout(600);
const built=await p.evaluate(()=>window.__townDebug.town().buildings.filter(b=>b.design==='townOffice').length);
const rt=await p.textContent('#runtime-error-message').catch(()=>'');console.log('RUNTIME:',rt);
await p.click('#hud-treasury');await p.waitForTimeout(500);
await p.click('#tab-council');await p.waitForTimeout(500);
const info={spot,built,note:await p.textContent('#council-note'),advisors:await p.$$eval('.advisor h4',e=>e.map(x=>x.textContent)),levels:await p.$$eval('.advisor',e=>e.map(x=>x.className))};
await p.screenshot({path:`${out}/22-council-advisors.png`});
info.errs=errs;console.log(JSON.stringify(info,null,1));
await b.close();
